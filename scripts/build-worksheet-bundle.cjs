const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const names=['authoring-plan','worksheet-layout','worksheet-document','worksheet-studio','worksheet-local-import','worksheet-source-tools','worksheet-classroom'];
const content='// Generated by scripts/build-worksheet-bundle.cjs. Edit the source modules.\n'+names.map(name=>`\n// ${name}.js\n${fs.readFileSync(path.join(root,'src/modules',name+'.js'),'utf8').replace(/\r\n/g,'\n')}`).join('\n');
fs.writeFileSync(path.join(root,'src/modules/worksheet-bundle.js'),content,'utf8');
console.log('Worksheet bundle built (ordered, no external dependencies)');
